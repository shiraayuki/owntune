#!/usr/bin/env bash
# Generates the app icon (three equalizer bars) for iOS and Android from one
# geometry. Re-run after changing a colour or the bars; needs ImageMagick
# with librsvg (`magick -list format | grep RSVG`).
#
# iOS: one 1024 px icon each for the default, dark and tinted appearance
#      (iOS 18 picks the one matching the home screen; older iOS uses the
#      default). Xcode makes the other sizes.
# Android: legacy mipmaps (before Android 8), an adaptive icon with a
#      monochrome layer for themed icons (Android 13+), and the small
#      notification icon for the player notification.
set -euo pipefail

root="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
ios="$root/ios/Runner/Assets.xcassets/AppIcon.appiconset"
res="$root/android/app/src/main/res"
tmp="$(mktemp -d)"
trap 'rm -rf "$tmp"' EXIT

coral='#ff7a59'    # the app's default accent
ink='#170b06'      # text on the accent (AppTheme accentText)
midnight='#0e0e12' # the dark theme's background

# The bars on a 1024 canvas: 110 wide, 74 apart, heights 275/500/350,
# bottom-aligned, the group centred.
bars() { # $1 = fill
  cat <<EOF
  <rect x="273" y="487" width="110" height="275" rx="55" fill="$1"/>
  <rect x="457" y="262" width="110" height="500" rx="55" fill="$1"/>
  <rect x="641" y="412" width="110" height="350" rx="55" fill="$1"/>
EOF
}

svg() { # $1 = background ('' for none), $2 = bar colour, $3 = corner radius
  echo '<svg xmlns="http://www.w3.org/2000/svg" width="1024" height="1024" viewBox="0 0 1024 1024">'
  [[ -n "$1" ]] && echo "  <rect width=\"1024\" height=\"1024\" rx=\"$3\" fill=\"$1\"/>"
  bars "$2"
  echo '</svg>'
}

# --- iOS: square, opaque (iOS rounds the corners itself) ---
rm -f "$ios"/*.png
svg "$coral" "$ink" 0 > "$tmp/ios.svg"
svg "$midnight" "$coral" 0 > "$tmp/ios-dark.svg"
svg '#000000' '#ffffff' 0 > "$tmp/ios-tinted.svg"
magick -background none "$tmp/ios.svg" -alpha off "$ios/AppIcon.png"
magick -background none "$tmp/ios-dark.svg" -alpha off "$ios/AppIcon-Dark.png"
magick -background none "$tmp/ios-tinted.svg" -alpha off -colorspace Gray "$ios/AppIcon-Tinted.png"
cat > "$ios/Contents.json" <<'EOF'
{
  "images" : [
    {
      "filename" : "AppIcon.png",
      "idiom" : "universal",
      "platform" : "ios",
      "size" : "1024x1024"
    },
    {
      "appearances" : [
        {
          "appearance" : "luminosity",
          "value" : "dark"
        }
      ],
      "filename" : "AppIcon-Dark.png",
      "idiom" : "universal",
      "platform" : "ios",
      "size" : "1024x1024"
    },
    {
      "appearances" : [
        {
          "appearance" : "luminosity",
          "value" : "tinted"
        }
      ],
      "filename" : "AppIcon-Tinted.png",
      "idiom" : "universal",
      "platform" : "ios",
      "size" : "1024x1024"
    }
  ],
  "info" : {
    "author" : "xcode",
    "version" : 1
  }
}
EOF

# --- Android: legacy mipmaps (rounded square on transparent) ---
svg "$coral" "$ink" 225 > "$tmp/legacy.svg"
for pair in mdpi:48 hdpi:72 xhdpi:96 xxhdpi:144 xxxhdpi:192; do
  dir="$res/mipmap-${pair%%:*}"
  mkdir -p "$dir"
  magick -background none -density 384 "$tmp/legacy.svg" -resize "${pair##*:}x${pair##*:}" "$dir/ic_launcher.png"
done

# --- Android: adaptive icon (Android 8+) with a monochrome layer ---
# 108 dp canvas; the bars sit inside the 66 dp safe zone.
mkdir -p "$res/mipmap-anydpi-v26" "$res/drawable" "$res/values"
cat > "$res/drawable/ic_launcher_foreground.xml" <<EOF
<?xml version="1.0" encoding="utf-8"?>
<!-- Generated by tool/make_icons.sh -->
<vector xmlns:android="http://schemas.android.com/apk/res/android"
    android:width="108dp"
    android:height="108dp"
    android:viewportWidth="108"
    android:viewportHeight="108">
    <path android:fillColor="$ink" android:pathData="M38.4,55.85 a3.6,3.6 0 0 1 7.2,0 v12.05 a3.6,3.6 0 0 1 -7.2,0 z"/>
    <path android:fillColor="$ink" android:pathData="M50.4,40.1 a3.6,3.6 0 0 1 7.2,0 v27.8 a3.6,3.6 0 0 1 -7.2,0 z"/>
    <path android:fillColor="$ink" android:pathData="M62.4,50.6 a3.6,3.6 0 0 1 7.2,0 v17.3 a3.6,3.6 0 0 1 -7.2,0 z"/>
</vector>
EOF
cat > "$res/mipmap-anydpi-v26/ic_launcher.xml" <<'EOF'
<?xml version="1.0" encoding="utf-8"?>
<!-- Generated by tool/make_icons.sh -->
<adaptive-icon xmlns:android="http://schemas.android.com/apk/res/android">
    <background android:drawable="@color/ic_launcher_background"/>
    <foreground android:drawable="@drawable/ic_launcher_foreground"/>
    <monochrome android:drawable="@drawable/ic_launcher_foreground"/>
</adaptive-icon>
EOF
cat > "$res/values/ic_launcher_background.xml" <<EOF
<?xml version="1.0" encoding="utf-8"?>
<!-- Generated by tool/make_icons.sh -->
<resources>
    <color name="ic_launcher_background">$coral</color>
</resources>
EOF

# --- Android: notification icon (white on transparent, 24 dp) ---
cat > "$res/drawable/ic_stat_owntune.xml" <<'EOF'
<?xml version="1.0" encoding="utf-8"?>
<!-- Generated by tool/make_icons.sh -->
<vector xmlns:android="http://schemas.android.com/apk/res/android"
    android:width="24dp"
    android:height="24dp"
    android:viewportWidth="24"
    android:viewportHeight="24">
    <path android:fillColor="#FFFFFFFF" android:pathData="M5.5,12.9 a1.5,1.5 0 0 1 3,0 v3.6 a1.5,1.5 0 0 1 -3,0 z"/>
    <path android:fillColor="#FFFFFFFF" android:pathData="M10.5,7.5 a1.5,1.5 0 0 1 3,0 v9 a1.5,1.5 0 0 1 -3,0 z"/>
    <path android:fillColor="#FFFFFFFF" android:pathData="M15.5,11.1 a1.5,1.5 0 0 1 3,0 v5.4 a1.5,1.5 0 0 1 -3,0 z"/>
</vector>
EOF

echo "Icons written to $ios and $res"
