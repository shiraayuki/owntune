// Embeds the audio fixtures into integration_test/support/fixture_data.dart,
// so integration tests can run on devices (Android emulator, iPhone) that
// cannot read the host's test/fixtures folder.
//
// Usage (after changing test/fixtures/audio):
//   dart run tool/embed_fixtures.dart
import 'dart:convert';
import 'dart:io';
import 'dart:typed_data';

const _source = 'test/fixtures/audio';
const _target = 'integration_test/support/fixture_data.dart';

/// The fixture files in [dir] by name; everything except the README.
Map<String, Uint8List> audioFixtures(Directory dir) {
  final files =
      dir
          .listSync()
          .whereType<File>()
          .where((f) => !f.path.endsWith('README.md'))
          .toList()
        ..sort((a, b) => a.path.compareTo(b.path));
  return {for (final f in files) f.uri.pathSegments.last: f.readAsBytesSync()};
}

void main() {
  final out = StringBuffer()
    ..writeln('// GENERATED by tool/embed_fixtures.dart from $_source.')
    ..writeln('// Do not edit by hand; test/tool/embed_fixtures_test.dart')
    ..writeln('// fails when this file is stale.')
    ..writeln()
    ..writeln('/// Base64 of each audio fixture, by file name.')
    ..writeln('const Map<String, String> fixtureData = {');
  for (final MapEntry(:key, :value) in audioFixtures(
    Directory(_source),
  ).entries) {
    out.writeln("  '$key':");
    out.writeln("      '${base64Encode(value)}',");
  }
  out.writeln('};');
  File(_target).writeAsStringSync(out.toString());
  stdout.writeln('wrote $_target');
}
